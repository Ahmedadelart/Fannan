// Builds the fonts artists can choose (round 12) from config/fonts.json:
//   - copies the woff2 files from the Fontsource packages into public/fonts/
//   - writes src/styles/fonts.generated.css (@font-face rules; a browser downloads a font only when
//     a page uses it)
//   - writes src/components/site/fonts.generated.ts (the typed registry)
// Run with `npm run fonts` after changing config/fonts.json; the outputs are committed, so builds
// don't need the Fontsource packages.

import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(join(root, "config/fonts.json"), "utf8"));
const out = join(root, "public/fonts");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const SUBSETS = { latin: ["latin", "latin-ext"], arabic: ["arabic", "latin"] };
let css = "/* Generated by scripts/fonts.mjs from config/fonts.json. Do not edit. */\n";
const entries = [];

for (const f of config.fonts) {
  const pkg = join(root, "node_modules", f.package);
  const base = f.package.split("/")[1];
  if (!existsSync(pkg)) throw new Error(`Missing package ${f.package}: run npm install`);
  const sheets = f.variable ? ["wght.css"] : f.weights.map((w) => `${w}.css`);
  let weights = f.weights ?? [];
  for (const sheet of sheets) {
    const text = readFileSync(join(pkg, sheet), "utf8");
    for (const block of text.split("/*").slice(1)) {
      const name = block.slice(0, block.indexOf("*/")).trim();
      // e.g. "cairo-arabic-wght-normal", "anton-latin-ext-400-normal"
      const m = new RegExp(`^${base}-(.+)-(wght|[0-9]+)-normal$`).exec(name);
      if (!m || !SUBSETS[f.script].includes(m[1])) continue;
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
      const weight = /font-weight:\s*([^;]+);/.exec(block)?.[1];
      if (!file || !range || !weight) continue;
      copyFileSync(join(pkg, "files", file), join(out, file));
      if (f.variable) weights = weight.split(" ").map(Number);
      css += `@font-face{font-family:"fn-${f.id}";font-style:normal;font-display:swap;font-weight:${weight};src:url(/fonts/${file}) format("woff2");unicode-range:${range.trim()}}\n`;
    }
  }
  entries.push({
    id: f.id,
    name: f.name,
    script: f.script,
    category: f.category,
    family: `"fn-${f.id}"`,
    headingWeight: f.headingWeight,
    // Variable fonts: [lightest, heaviest]; others: the weights there are.
    weights,
    variable: f.variable,
  });
}

writeFileSync(
  join(out, "LICENSE.txt"),
  [
    "The fonts in this folder are licensed under the SIL Open Font License, Version 1.1",
    "(https://openfontlicense.org). They come from Google Fonts via Fontsource; each font's",
    "copyright notice is in its Fontsource package (node_modules/@fontsource*/<font>/LICENSE).",
    "The list of fonts is in config/fonts.json.",
    "",
  ].join("\n"),
);
writeFileSync(join(root, "src/styles/fonts.generated.css"), css);
writeFileSync(
  join(root, "src/components/site/fonts.generated.ts"),
  `// Generated by scripts/fonts.mjs from config/fonts.json. Do not edit.\n\nexport const FONT_LIST = ${JSON.stringify(entries, null, 2)} as const;\n\nexport const FONT_PAIRS = ${JSON.stringify(config.pairs, null, 2)} as const;\n`,
);
console.log(`fonts: ${entries.length} fonts, ${config.pairs.length} pairs`);
